const wakeVectorsPath = "../crates/protocol/testdata/wake-vectors.json"

type wakeExpectation struct {
	TenantID       string `json:"tenant_id"`
	RelayDeviceID  string `json:"relay_device_id"`
	RelayKeySHA256 string `json:"relay_key_sha256"`
	WakeChallenge  string `json:"wake_challenge"`
	NowMs          int64  `json:"now_ms"`
}

func verifyWake(pub ed25519.PublicKey, artifact []byte, exp wakeExpectation) string {
	if !usableEd25519Key(pub) {
		return "key"
	}
	envelope, ok := strictSignedJSONObject(artifact, "claims sig", "")
	if !ok || !utf8.Valid(artifact) {
		return "envelope"
	}
	claims, ok := strictSignedJSONObject(envelope["claims"], "tenant_id relay_device_id relay_key_sha256 wake_challenge request_id target_mac ipv4_network gateway_mac issued_at_ms expires_at_ms", "")
	if !ok {
		return "envelope"
	}
	var sd signedWake
	if json.Unmarshal(artifact, &sd) != nil || !validSignedJSONString(claims["relay_device_id"]) {
		return "envelope"
	}
	sig, err := wakeHex(sd.Sig, ed25519.SignatureSize)
	if err != nil {
		return "envelope"
	}
	c := sd.Claims
	if string(claims["issued_at_ms"]) != strconv.FormatInt(c.IssuedAtMs, 10) ||
		string(claims["expires_at_ms"]) != strconv.FormatInt(c.ExpiresAtMs, 10) {
		return "envelope"
	}
	msg, err := wakePreimage(c)
	if err != nil {
		return "envelope"
	}
	if !ed25519.Verify(pub, msg, sig) {
		return "signature"
	}
	if c.RelayDeviceID != exp.RelayDeviceID {
		return "device"
	}
	if !strings.EqualFold(c.TenantID, exp.TenantID) {
		return "tenant"
	}
	if c.RelayKeySHA256 != exp.RelayKeySHA256 {
		return "key_fp"
	}
	if c.WakeChallenge != exp.WakeChallenge {
		return "challenge"
	}
	if !validWakeLifetime(c.IssuedAtMs, c.ExpiresAtMs) {
		return "lifetime"
	}
	if exp.NowMs <= math.MaxInt64-wakeClockSkew && c.IssuedAtMs > exp.NowMs+wakeClockSkew {
		return "not_yet_valid"
	}
	if exp.NowMs >= c.ExpiresAtMs {
		return "expired"
	}
	return "ok"
}

type wakeVector struct {
	Name         string          `json:"name"`
	Artifact     string          `json:"artifact"`
	PinnedKeyHex string          `json:"pinned_public_key_hex"`
	Expectation  wakeExpectation `json:"expectation"`
	Expect       string          `json:"expect"`
	PreimageHex  string          `json:"preimage_hex,omitempty"`
}

type wakeVectorFile struct {
	Comment string       `json:"comment"`
	Tests   []wakeVector `json:"wake_vectors"`
}

func firstWakeDirective(t *testing.T) directiveVector {
	t.Helper()
	data, err := os.ReadFile(directiveVectorsPath)
	if err != nil {
		t.Fatal(err)
	}
	var file directiveVectorFile
	if err := json.Unmarshal(data, &file); err != nil {
		t.Fatal(err)
	}
	return file.DirectiveTests[0]
}

func buildWakeVectors(t *testing.T) wakeVectorFile {
	t.Helper()
	priv := ed25519.NewKeyFromSeed(seedBytes(0x11))
	pub := hex.EncodeToString(priv.Public().(ed25519.PublicKey))
	directive := firstWakeDirective(t)
	if pub != directive.PinnedKeyHex || directive.Expect != "ok" {
		t.Fatal("cross-domain fixture must be positive and use the same pinned key")
	}
	const issued int64 = 1_800_000_000_000
	base := WakeClaims{
		TenantID: "11111111-2222-4333-8444-555555555555", RelayDeviceID: "relay-é",
		RelayKeySHA256: directive.Expectation.KeyFP, WakeChallenge: "000102030405060708090a0b0c0d0e0f",
		RequestID: "bbbbbbbb-cccc-4ddd-8eee-ffffffffffff", TargetMAC: "aa:bb:cc:dd:ee:fe",
		IPv4Network: "192.168.1.0/24", GatewayMAC: "02:12:34:56:78:90",
		IssuedAtMs: issued, ExpiresAtMs: issued + wakeMaxTTL,
	}
	exp := wakeExpectation{base.TenantID, base.RelayDeviceID, base.RelayKeySHA256, base.WakeChallenge, issued + 1_000}
	file := wakeVectorFile{Comment: "Generated by TestWakeGoldenVectors. First failure wins: key, envelope, signature, device, tenant, key_fp, challenge, lifetime, not_yet_valid, expired."}
	add := func(name, artifact, pin string, expectation wakeExpectation, want, preimage string) {
		file.Tests = append(file.Tests, wakeVector{name, artifact, pin, expectation, want, preimage})
	}
	encode := func(v any) string {
		t.Helper()
		b, err := json.Marshal(v)
		if err != nil {
			t.Fatal(err)
		}
		return string(b)
	}
	preimage := func(c WakeClaims) []byte {
		t.Helper()
		b, err := wakePreimage(c)
		if err != nil {
			t.Fatal(err)
		}
		return b
	}
	artifact, err := SignWake(priv, base)
	if err != nil {
		t.Fatal(err)
	}
	good := string(artifact)
	add("valid", good, pub, exp, "ok", hex.EncodeToString(preimage(base)))
	short := base
	short.IssuedAtMs, short.ExpiresAtMs = -1, 0
	short.IPv4Network = "192.168.1.0/30"
	shortArtifact, err := SignWake(priv, short)
	if err != nil {
		t.Fatal(err)
	}
	shortExp := exp
	shortExp.NowMs = -1
	add("minimum lifetime", string(shortArtifact), pub, shortExp, "ok", hex.EncodeToString(preimage(short)))
	add("directive artifact", directive.Artifact, pub, exp, "envelope", "")
	for _, pin := range []struct{ name, hex string }{
		{"missing pin", ""}, {"short pin", "1234"}, {"weak pin", strings.Repeat("00", 32)},
		{"non-curve pin", "02" + strings.Repeat("00", 31)},
	} {
		add(pin.name, "{", pin.hex, exp, "key", "")
	}
	for _, tc := range []struct{ name, artifact string }{
		{"bad JSON", "{"},
		{"array envelope", "[]"},
		{"array claims", `{"claims":[],"sig":""}`},
		{"trailing JSON", good + " {}"},
		{"missing timestamp", strings.Replace(good, `"issued_at_ms":1800000000000,`, "", 1)},
		{"duplicate timestamp", strings.Replace(good, `"issued_at_ms":`, `"issued_at_ms":0,"issued_at_ms":`, 1)},
		{"null timestamp", strings.Replace(good, "1800000000000", "null", 1)},
		{"negative zero timestamp", strings.Replace(good, "1800000000000", "-0", 1)},
		{"missing gateway", strings.Replace(good, `"gateway_mac":"02:12:34:56:78:90",`, "", 1)},
		{"unpaired surrogate in relay", strings.Replace(good, "relay-é", `relay-\ud800`, 1)},
		{"bad signature hex", good[:len(good)-3] + `z"}`},
	} {
		add(tc.name, tc.artifact, pub, exp, "envelope", "")
	}
	var signed signedWake
	if err := json.Unmarshal(artifact, &signed); err != nil {
		t.Fatal(err)
	}
	var sd SignedDirective
	if err := json.Unmarshal([]byte(directive.Artifact), &sd); err != nil {
		t.Fatal(err)
	}
	add("directive signature in wake envelope", encode(signedWake{base, sd.Sig}), pub, exp, "signature", "")
	for _, tc := range []struct {
		name string
		edit func(*WakeClaims)
	}{
		{"tenant_id", func(c *WakeClaims) { c.TenantID = "21111111-2222-4333-8444-555555555555" }},
		{"relay_device_id", func(c *WakeClaims) { c.RelayDeviceID += "x" }},
		{"relay_key_sha256", func(c *WakeClaims) { c.RelayKeySHA256 = strings.Repeat("ab", 32) }},
		{"wake_challenge", func(c *WakeClaims) { c.WakeChallenge = strings.Repeat("ab", 16) }},
		{"request_id", func(c *WakeClaims) { c.RequestID = "abbbbbbb-cccc-4ddd-8eee-ffffffffffff" }},
		{"target_mac", func(c *WakeClaims) { c.TargetMAC = "aa:bb:cc:dd:ee:ff" }},
		{"network address", func(c *WakeClaims) { c.IPv4Network = "192.168.2.0/24" }},
		{"network prefix", func(c *WakeClaims) { c.IPv4Network = "192.168.1.0/25" }},
		{"gateway_mac", func(c *WakeClaims) { c.GatewayMAC = "02:12:34:56:78:91" }},
		{"issued_at_ms", func(c *WakeClaims) { c.IssuedAtMs++ }},
		{"expires_at_ms", func(c *WakeClaims) { c.ExpiresAtMs-- }},
	} {
		v := signed
		tc.edit(&v.Claims)
		add("tampered "+tc.name, encode(v), pub, exp, "signature", "")
	}
	for _, tc := range []struct {
		name string
		edit func(*WakeClaims)
	}{
		{"uppercase MAC", func(c *WakeClaims) { c.TargetMAC = strings.ToUpper(c.TargetMAC) }},
		{"host bits set", func(c *WakeClaims) { c.IPv4Network = "192.168.1.1/24" }},
		{"prefix 15", func(c *WakeClaims) { c.IPv4Network = "192.168.0.0/15" }},
		{"prefix 31", func(c *WakeClaims) { c.IPv4Network = "192.168.1.0/31" }},
		{"multicast target", func(c *WakeClaims) { c.TargetMAC = "01:00:5e:00:00:01" }},
		{"zero target", func(c *WakeClaims) { c.TargetMAC = "00:00:00:00:00:00" }},
		{"zero gateway", func(c *WakeClaims) { c.GatewayMAC = "00:00:00:00:00:00" }},
		{"broadcast gateway", func(c *WakeClaims) { c.GatewayMAC = "ff:ff:ff:ff:ff:ff" }},
		{"uppercase UUID", func(c *WakeClaims) { c.RequestID = strings.ToUpper(c.RequestID) }},
		{"uppercase fingerprint", func(c *WakeClaims) { c.RelayKeySHA256 = strings.ToUpper(c.RelayKeySHA256) }},
	} {
		v := signed
		tc.edit(&v.Claims)
		if _, err := SignWake(priv, v.Claims); err == nil {
			t.Fatalf("signer accepted %s", tc.name)
		}
		add(tc.name, encode(v), pub, exp, "envelope", "")
	}
	for _, tc := range []struct {
		name, want string
		edit       func(*wakeExpectation)
	}{
		{"wrong device", "device", func(e *wakeExpectation) { e.RelayDeviceID += "x"; e.TenantID = "" }},
		{"wrong tenant", "tenant", func(e *wakeExpectation) { e.TenantID = ""; e.RelayKeySHA256 = strings.Repeat("ab", 32) }},
		{"wrong fingerprint", "key_fp", func(e *wakeExpectation) {
			e.RelayKeySHA256 = strings.Repeat("ab", 32)
			e.WakeChallenge = strings.Repeat("ab", 16)
		}},
		{"wrong challenge", "challenge", func(e *wakeExpectation) { e.WakeChallenge = strings.Repeat("ab", 16); e.NowMs = base.ExpiresAtMs }},
		{"future boundary", "ok", func(e *wakeExpectation) { e.NowMs = issued - wakeClockSkew }},
		{"not yet valid", "not_yet_valid", func(e *wakeExpectation) { e.NowMs = issued - wakeClockSkew - 1 }},
		{"expiry boundary", "expired", func(e *wakeExpectation) { e.NowMs = base.ExpiresAtMs }},
		{"clock addition overflow", "expired", func(e *wakeExpectation) { e.NowMs = math.MaxInt64 }},
	} {
		e := exp
		tc.edit(&e)
		add(tc.name, good, pub, e, tc.want, "")
	}
	for _, tc := range []struct {
		name       string
		start, end int64
	}{
		{"zero lifetime", issued, issued},
		{"60001 ms lifetime", issued, issued + 60001},
		{"negative lifetime", issued, issued - 1},
		{"lifetime overflow", math.MinInt64 + 1, math.MaxInt64 - 1},
	} {
		c := base
		c.IssuedAtMs, c.ExpiresAtMs = tc.start, tc.end
		if _, err := SignWake(priv, c); err == nil {
			t.Fatalf("signer accepted %s", tc.name)
		}
		// Sign the preimage directly to exercise verifier checks after authentication.
		v := signedWake{c, hex.EncodeToString(ed25519.Sign(priv, preimage(c)))}
		add(tc.name, encode(v), pub, exp, "lifetime", "")
	}
	return file
}

func TestWakeGoldenVectors(t *testing.T) {
	file := buildWakeVectors(t)
	want, err := json.MarshalIndent(file, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	want = append(want, '\n')
	if os.Getenv("UPDATE_WAKE_VECTORS") == "1" {
		if err := os.WriteFile(wakeVectorsPath, want, 0644); err != nil {
			t.Fatal(err)
		}
	}
	data, err := os.ReadFile(wakeVectorsPath)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(data, want) {
		t.Fatal("wake vectors drifted: regenerate with UPDATE_WAKE_VECTORS=1 go test -run TestWakeGoldenVectors .")
	}
	if err := json.Unmarshal(data, &file); err != nil {
		t.Fatal(err)
	}
	for _, tc := range file.Tests {
		t.Run(tc.Name, func(t *testing.T) {
			pub, err := hex.DecodeString(tc.PinnedKeyHex)
			if err != nil {
				t.Fatal(err)
			}
			if got := verifyWake(pub, []byte(tc.Artifact), tc.Expectation); got != tc.Expect {
				t.Errorf("got %q, want %q", got, tc.Expect)
			}
		})
	}
}

func TestWakeSignatureRefusedAsDirective(t *testing.T) {
	wake := buildWakeVectors(t).Tests[0]
	directive := firstWakeDirective(t)
	var sw signedWake
	var sd SignedDirective
	if err := json.Unmarshal([]byte(wake.Artifact), &sw); err != nil {
		t.Fatal(err)
	}
	if err := json.Unmarshal([]byte(directive.Artifact), &sd); err != nil {
		t.Fatal(err)
	}
	sd.Sig = sw.Sig
	artifact, err := json.Marshal(sd)
	if err != nil {
		t.Fatal(err)
	}
	pub, err := hex.DecodeString(directive.PinnedKeyHex)
	if err != nil {
		t.Fatal(err)
	}
	e := directive.Expectation
	_, err = VerifyDirective(pub, string(artifact), DirectiveExpectation{
		DeviceID: e.DeviceID, TenantID: e.TenantID, KeyFP: e.KeyFP, NowMs: e.NowMs,
	})
	if refusal, ok := err.(*DirectiveVerifyError); !ok || refusal.Code != DirectiveRefusedSignature {
		t.Fatalf("directive verifier returned %v, want signature refusal", err)
	}
}
