const runReceiptVectorsPath = "../crates/protocol/testdata/run-receipt-vectors.json"

type runReceiptVector struct {
	Name        string `json:"name"`
	Artifact    string `json:"artifact"`
	Expect      string `json:"expect"`
	PreimageHex string `json:"preimage_hex,omitempty"`
}

type runReceiptVectorFile struct {
	Comment      string             `json:"comment"`
	DeviceKeyHex string             `json:"device_public_key_hex"`
	Tests        []runReceiptVector `json:"run_receipt_vectors"`
}

func signRunReceiptForTest(priv ed25519.PrivateKey, c RunReceiptClaims) (signedRunReceipt, []byte, error) {
	msg, err := runReceiptPreimage(c)
	if err != nil {
		return signedRunReceipt{}, nil, err
	}
	return signedRunReceipt{c, hex.EncodeToString(ed25519.Sign(priv, msg))}, msg, nil
}

func buildRunReceiptVectors(t *testing.T) runReceiptVectorFile {
	t.Helper()
	priv := ed25519.NewKeyFromSeed(seedBytes(0x22))
	pub := priv.Public().(ed25519.PublicKey)
	file := runReceiptVectorFile{
		Comment:      "Generated by TestRunReceiptGoldenVectors. Errors: key, envelope, signature.",
		DeviceKeyHex: hex.EncodeToString(pub),
	}
	encode := func(v signedRunReceipt) string {
		t.Helper()
		data, err := json.Marshal(v)
		if err != nil {
			t.Fatal(err)
		}
		return string(data)
	}
	add := func(name, artifact, expect string) {
		file.Tests = append(file.Tests, runReceiptVector{Name: name, Artifact: artifact, Expect: expect})
	}
	zero, minusOne, timeout := int32(0), int32(-1), int32(258)
	base := RunReceiptClaims{
		TenantID: "11111111-2222-4333-8444-555555555555", DeviceID: "device-é",
		SessionID: "aaaaaaaa-bbbb-4ccc-8ddd-eeeeeeeeeeee", RequestID: "bbbbbbbb-cccc-4ddd-8eee-ffffffffffff",
		Shell: "powershell", RunAs: "system", ExecSHA256: strings.Repeat("ab", 32),
		Outcome: "exited", ExitCode: &zero, FinishedAtMs: 1800000000000,
	}
	negativeExit := base
	negativeExit.ExitCode, negativeExit.Shell, negativeExit.RunAs = &minusOne, "cmd", "user"
	timedOut := base
	timedOut.Outcome, timedOut.ExitCode = "timed_out", &timeout
	failed := base
	failed.Outcome, failed.ExitCode = "start_failed", nil
	truncated := base
	truncated.Truncated, truncated.DeviceID, truncated.FinishedAtMs = true, strings.Repeat("é", 128), -1
	for _, tc := range []struct {
		name string
		c    RunReceiptClaims
	}{
		{"exited 0", base}, {"exited -1", negativeExit}, {"timed out", timedOut},
		{"start failed", failed}, {"truncated at maximum device ID length", truncated},
	} {
		signed, msg, err := signRunReceiptForTest(priv, tc.c)
		if err != nil {
			t.Fatal(err)
		}
		file.Tests = append(file.Tests, runReceiptVector{tc.name, encode(signed), "ok", hex.EncodeToString(msg)})
	}
	signed, msg, err := signRunReceiptForTest(priv, base)
	if err != nil {
		t.Fatal(err)
	}
	good := encode(signed)

	for _, tc := range []struct {
		field string
		edit  func(*RunReceiptClaims)
	}{
		{"tenant_id", func(c *RunReceiptClaims) { c.TenantID = "21111111-2222-4333-8444-555555555555" }},
		{"device_id", func(c *RunReceiptClaims) { c.DeviceID += "x" }},
		{"session_id", func(c *RunReceiptClaims) { c.SessionID = "baaaaaaa-bbbb-4ccc-8ddd-eeeeeeeeeeee" }},
		{"request_id", func(c *RunReceiptClaims) { c.RequestID = "abbbbbbb-cccc-4ddd-8eee-ffffffffffff" }},
		{"shell", func(c *RunReceiptClaims) { c.Shell = "cmd" }},
		{"run_as", func(c *RunReceiptClaims) { c.RunAs = "user" }},
		{"exec_sha256", func(c *RunReceiptClaims) { c.ExecSHA256 = strings.Repeat("cd", 32) }},
		{"outcome", func(c *RunReceiptClaims) { c.Outcome = "timed_out" }},
		{"exit_code", func(c *RunReceiptClaims) { c.ExitCode = &minusOne }},
		{"truncated", func(c *RunReceiptClaims) { c.Truncated = true }},
		{"finished_at_ms", func(c *RunReceiptClaims) { c.FinishedAtMs++ }},
	} {
		v := signed
		tc.edit(&v.Claims)
		add("tampered "+tc.field, encode(v), "signature")
	}
	for _, tc := range []struct {
		name string
		edit func(*RunReceiptClaims)
	}{
		{"unknown shell", func(c *RunReceiptClaims) { c.Shell = "bash" }},
		{"unknown run_as", func(c *RunReceiptClaims) { c.RunAs = "admin" }},
		{"unknown outcome", func(c *RunReceiptClaims) { c.Outcome = "unknown" }},
		{"numeric start failure exit code", func(c *RunReceiptClaims) { c.Outcome = "start_failed" }},
		{"null exited exit code", func(c *RunReceiptClaims) { c.ExitCode = nil }},
		{"truncated start failure", func(c *RunReceiptClaims) { *c = failed; c.Truncated = true }},
		{"uppercase UUID", func(c *RunReceiptClaims) { c.SessionID = strings.ToUpper(c.SessionID) }},
		{"uppercase exec hash", func(c *RunReceiptClaims) { c.ExecSHA256 = strings.ToUpper(c.ExecSHA256) }},
		{"oversized UTF-8 device ID", func(c *RunReceiptClaims) { c.DeviceID = strings.Repeat("é", 129) }},
	} {
		v := signed
		tc.edit(&v.Claims)
		if _, _, err := signRunReceiptForTest(priv, v.Claims); err == nil {
			t.Fatalf("signer accepted %s", tc.name)
		}
		add(tc.name, encode(v), "envelope")
	}
	for _, tc := range []struct{ name, artifact string }{
		{"uppercase signature", encode(signedRunReceipt{base, strings.ToUpper(signed.Sig)})},
		{"trailing JSON", good + " {}"},
		{"duplicate claim", strings.Replace(good, `"shell":`, `"shell":"cmd","shell":`, 1)},
		{"duplicate envelope field", strings.Replace(good, `"sig":`, `"sig":"","sig":`, 1)},
		{"unknown claim", strings.Replace(good, `"shell":`, `"extra":0,"shell":`, 1)},
		{"unknown JSON version", `{"version":2,` + good[1:]},
		{"reserved JSON flags", strings.Replace(good, `"truncated":`, `"flags":2,"truncated":`, 1)},
		{"supplied preimage", `{"preimage_hex":"` + hex.EncodeToString(msg) + `",` + good[1:]},
		{"missing exit code on start failure", strings.Replace(file.Tests[3].Artifact, `"exit_code":null,`, "", 1)},
		{"unpaired device ID surrogate", strings.Replace(good, "device-é", `device-\ud800`, 1)},
		{"array envelope", "[]"},
		{"array claims", `{"claims":[],"sig":""}`},
		{"negative zero exit code", strings.Replace(good, `"exit_code":0`, `"exit_code":-0`, 1)},
	} {
		add(tc.name, tc.artifact, "envelope")
	}
	add("bad signature", encode(signedRunReceipt{base, strings.Repeat("00", 64)}), "signature")
	for _, tc := range []struct {
		name   string
		offset int
	}{
		{"unknown preimage version", 16},
		{"reserved preimage flag bit", len(msg) - 9},
	} {
		other := bytes.Clone(msg)
		other[tc.offset] = 2
		add(tc.name, encode(signedRunReceipt{base, hex.EncodeToString(ed25519.Sign(priv, other))}), "signature")
	}
	for _, domain := range otherDeviceSigningMessages(t, pub, base) {
		sig := ed25519.Sign(priv, domain.message)
		if !ed25519.Verify(pub, domain.message, sig) {
			t.Fatalf("invalid %s fixture signature", domain.name)
		}
		add(domain.name+" signature", encode(signedRunReceipt{base, hex.EncodeToString(sig)}), "signature")
	}
	add("RMTDIRECTIVEv1 artifact", firstWakeDirective(t).Artifact, "envelope")
	add("RMTWAKEv1 artifact", buildWakeVectors(t).Tests[0].Artifact, "envelope")
	return file
}

type deviceSigningMessage struct {
	name    string
	message []byte
}

func otherDeviceSigningMessages(t *testing.T, pub ed25519.PublicKey, c RunReceiptClaims) []deviceSigningMessage {
	t.Helper()
	tenant, err := uuidBytes(c.TenantID)
	if err != nil {
		t.Fatal(err)
	}
	session, err := uuidBytes(c.SessionID)
	if err != nil {
		t.Fatal(err)
	}
	request, err := uuidBytes(c.RequestID)
	if err != nil {
		t.Fatal(err)
	}

	// Mirror the Rust protocol's agent_auth and session_binding preimages.
	auth := canonicalWriter{buf: []byte("RMTAGENTAUTHv1\x00\x00")}
	auth.u8(1)
	auth.lpStr(c.DeviceID)
	auth.lpStr(c.TenantID)
	auth.lpStr(strings.Repeat("n", 32))

	bind := canonicalWriter{buf: []byte("RMTSESSBINDv1\x00\x00\x00")}
	bind.u8(1)
	bind.raw16(session)
	for _, fill := range []string{"a", "b", "c", "d"} {
		bind.buf = append(bind.buf, strings.Repeat(fill, 32)...)
	}
	bind.u8(1)

	bindV2 := canonicalWriter{buf: []byte("RMTSESSBINDv2\x00")}
	bindV2.u8(2)
	bindV2.raw16(session)
	bindV2.buf = append(bindV2.buf, strings.Repeat("a", 32)...)
	bindV2.buf = append(bindV2.buf, strings.Repeat("b", 32)...)
	bindV2.buf = append(bindV2.buf, pub...)
	consolePub := ed25519.NewKeyFromSeed(seedBytes(0x33)).Public().(ed25519.PublicKey)
	bindV2.buf = append(bindV2.buf, consolePub...)
	commitment := sha256.Sum256([]byte("RMTBIND-COMMIT-v2\x00" + strings.Repeat("d", 32)))
	bindV2.buf = append(bindV2.buf, commitment[:]...)
	bindV2.buf = append(bindV2.buf, strings.Repeat("c", 32)...)
	bindV2.u8(1)

	fp := UploadKeyFingerprint(pub)
	ack, err := directiveAckSigningBytes(c.TenantID, c.DeviceID, c.RequestID,
		hex.EncodeToString(fp[:]), "issued", "accepted", c.FinishedAtMs, "")
	if err != nil {
		t.Fatal(err)
	}
	upload := UploadPreimage(UploadSigFields{
		Audience: "https://example.invalid", Op: UploadOpFinish, Path: "/agent/recordings/" + c.RequestID + "/finish",
		TenantID: tenant, DeviceID: c.DeviceID, KeyFP: fp, RecordingID: request, Generation: 1,
		BodySHA256: sha256.Sum256(nil), TimestampMs: uint64(c.FinishedAtMs),
	})
	return []deviceSigningMessage{
		{"RMTAGENTAUTHv1", auth.buf}, {"RMTSESSBINDv1", bind.buf}, {"RMTSESSBINDv2", bindV2.buf},
		{"RMT-AUDIT-SIGN-v1", agentAuditSigningBytes(c.ExecSHA256)}, {"RMTDIRACKv1", ack}, {"RMTAGENTUPLOADv1", upload},
	}
}

func TestRunReceiptGoldenVectors(t *testing.T) {
	file := buildRunReceiptVectors(t)
	want, err := json.MarshalIndent(file, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	want = append(want, '\n')
	if os.Getenv("UPDATE_RUN_RECEIPT_VECTORS") == "1" {
		if err := os.WriteFile(runReceiptVectorsPath, want, 0644); err != nil {
			t.Fatal(err)
		}
	}
	data, err := os.ReadFile(runReceiptVectorsPath)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(data, want) {
		t.Fatal("run receipt vectors drifted: regenerate with UPDATE_RUN_RECEIPT_VECTORS=1 go test -run TestRunReceiptGoldenVectors .")
	}
	if err := json.Unmarshal(data, &file); err != nil {
		t.Fatal(err)
	}
	pub, err := hex.DecodeString(file.DeviceKeyHex)
	if err != nil {
		t.Fatal(err)
	}
	for _, tc := range file.Tests {
		t.Run(tc.Name, func(t *testing.T) {
			c, err := VerifyRunReceipt(pub, []byte(tc.Artifact))
			got := "ok"
			if err != nil {
				refusal, ok := err.(runReceiptError)
				if !ok {
					t.Fatal(err)
				}
				got = string(refusal)
			}
			if got != tc.Expect {
				t.Fatalf("got %q, want %q", got, tc.Expect)
			}
			if c != nil {
				msg, err := runReceiptPreimage(*c)
				if err != nil || hex.EncodeToString(msg) != tc.PreimageHex {
					t.Fatalf("preimage mismatch: %x (%v)", msg, err)
				}
			}
		})
	}
}
