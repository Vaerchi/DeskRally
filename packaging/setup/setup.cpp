// Read a pass or attestation beside the exe: same open as enrollment.token (no write/delete
// sharing, never through a final-component reparse point, regular file only), at most 4 KiB.
static bool ReadSignedFile(const std::wstring& path, std::string& out) {
    HandleGuard h(CreateFileW(path.c_str(), GENERIC_READ, FILE_SHARE_READ, nullptr, OPEN_EXISTING,
                              FILE_FLAG_OPEN_REPARSE_POINT, nullptr));
    if (!h.valid() || !IsRegularHandle(h.get())) return false;
    std::vector<char> buf(dp::kMaxSignedObject + 1);
    DWORD total = 0;
    for (;;) {
        DWORD n = 0;
        if (!ReadFile(h.get(), buf.data() + total, static_cast<DWORD>(buf.size() - total), &n, nullptr)) return false;
        if (n == 0) break;
        total += n;
        if (total == buf.size()) break;
    }
    if (total > dp::kMaxSignedObject) return false;
    out.assign(buf.data(), total);
    return true;
}

// Every value here passed a charset check (ASCII only), so widening byte-by-byte is exact.
static std::wstring Widen(const std::string& s) { return std::wstring(s.begin(), s.end()); }

struct PassBundle {
    dp::DeploymentPass pass;
    dp::AgentRelease release;
    std::wstring passSha256;  // of the exact pass file: binds the elevated run to what was shown
};

// Read and verify both signed files against the compiled-in root key, on this computer's clock
// (best-effort, docs/48 "Clock limitation"). Every refusal is fatal and named for the guest.
static bool LoadPassBundle(const std::wstring& dir, PassBundle& out, std::wstring& err) {
    std::string passRaw, relRaw;
    if (!ReadSignedFile(dir + L"\\deployment-pass.json", passRaw) || !ReadSignedFile(dir + L"\\agent-release.json", relRaw)) {
        err = L"deployment-pass.json or agent-release.json is missing or unreadable.\n\n"
              L"Extract ALL files from the installer bundle into one folder, then run DeskRallySetup.exe from there.";
        return false;
    }
    dp::RootKey root;
    if (!root.Load(SETUP_PASS_ROOT_KEY).ok()) {
        err = L"This copy of Setup is damaged (invalid root key). Download a fresh installer.";
        return false;
    }
    const long long now = dp::UnixNow();
    dp::Result r = dp::VerifyPass(root, passRaw, now, out.pass);
    if (!r.ok()) {
        err = r.kind == dp::Kind::Validity
                  ? L"This installer's deployment pass has expired, or this computer's date and time are wrong.\n\nCheck the clock, then download a fresh installer from your support provider."
                  : L"This installer's deployment pass is not valid. Download a fresh installer from your support provider.";
        return false;
    }
    if (!out.pass.for_setup) {
        err = L"This installer's deployment pass does not allow installation.";
        return false;
    }
    r = dp::VerifyRelease(root, relRaw, now, out.release);
    if (!r.ok()) {
        err = r.kind == dp::Kind::Validity
                  ? L"This installer's agent release has expired, or this computer's date and time are wrong.\n\nDownload a fresh installer from your support provider."
                  : L"This installer's agent release file is not valid. Download a fresh installer from your support provider.";
        return false;
    }
    if (!dp::PassAdmitsRelease(out.pass, out.release)) {
        err = L"This agent version is older than the deployment pass allows. Download a fresh installer.";
        return false;
    }
    unsigned char d[32];
    if (!dp::Sha256({{passRaw.data(), passRaw.size()}}, d)) {
        err = L"Could not hash the deployment pass.";
        return false;
    }
    static const wchar_t kHex[] = L"0123456789abcdef";
    out.passSha256.clear();
    for (unsigned char c : d) {
        out.passSha256.push_back(kHex[c >> 4]);
        out.passSha256.push_back(kHex[c & 15]);
    }
    return true;
}
