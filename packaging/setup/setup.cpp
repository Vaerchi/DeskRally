// ---- Own path ------------------------------------------------------------

static std::wstring GetOwnPath() {
    wchar_t buf[MAX_PATH + 1] = {};
    DWORD len = GetModuleFileNameW(nullptr, buf, MAX_PATH);
    if (len == 0 || len >= MAX_PATH) return {};
    return std::wstring(buf, len);
}

static std::wstring GetOwnDir(const std::wstring& ownPath) {
    size_t slash = ownPath.rfind(L'\\');
    if (slash == std::wstring::npos) return {};
    return ownPath.substr(0, slash);
}

// ---- Source-path safety --------------------------------------------------

// Rejects UNC paths, network drives, unknown drive types.
static bool IsDriveFixed(const std::wstring& absPath) {
    if (absPath.size() < 3) return false;
    wchar_t d = absPath[0];
    if (!((d >= L'A' && d <= L'Z') || (d >= L'a' && d <= L'z'))) return false;
    if (absPath[1] != L':' || absPath[2] != L'\\') return false;
    wchar_t root[4] = { d, L':', L'\\', L'\0' };
    return GetDriveTypeW(root) == DRIVE_FIXED;
}

// GetFileAttributesW returns the link's attributes (not the target's) for symlinks,
// so FILE_ATTRIBUTE_REPARSE_POINT is set on any junction, symlink, or mount point.
static bool HasReparseInPath(const std::wstring& path) {
    size_t pos = 3; // skip "X:\" â€” drive root already checked by IsDriveFixed
    while (pos <= path.size()) {
        size_t next = path.find(L'\\', pos);
        std::wstring prefix = (next == std::wstring::npos) ? path : path.substr(0, next);
        DWORD attr = GetFileAttributesW(prefix.c_str());
        if (attr != INVALID_FILE_ATTRIBUTES && (attr & FILE_ATTRIBUTE_REPARSE_POINT)) return true;
        if (next == std::wstring::npos) break;
        pos = next + 1;
    }
    return false;
}

bool PathLocks::hold(const std::wstring& path, bool includeLeaf) {
    if (!IsDriveFixed(path)) return false;
    size_t pos = 3;
    for (;;) {
        size_t next = path.find(L'\\', pos);
        if (next == std::wstring::npos && !includeLeaf) break;
        std::wstring prefix = next == std::wstring::npos ? path : path.substr(0, next);
        // FILE_LIST_DIRECTORY participates in Windows share-access checks; attributes-only
        // handles do NOT prevent rename even when FILE_SHARE_DELETE is absent (platform test).
        HANDLE h = CreateFileW(prefix.c_str(), FILE_LIST_DIRECTORY | FILE_READ_ATTRIBUTES,
            FILE_SHARE_READ | FILE_SHARE_WRITE, nullptr, OPEN_EXISTING,
            FILE_FLAG_OPEN_REPARSE_POINT | FILE_FLAG_BACKUP_SEMANTICS, nullptr);
        if (h == INVALID_HANDLE_VALUE) return false;
        handles.push_back(h);
        BY_HANDLE_FILE_INFORMATION info = {};
        if (!GetFileInformationByHandle(h, &info) || (info.dwFileAttributes & FILE_ATTRIBUTE_REPARSE_POINT)
            || !(info.dwFileAttributes & FILE_ATTRIBUTE_DIRECTORY)) return false;
        if (next == std::wstring::npos) break;
        pos = next + 1;
    }
    return true;
}

static bool IsRegularHandle(HANDLE h) {
    BY_HANDLE_FILE_INFORMATION info = {};
    return GetFileInformationByHandle(h, &info) &&
        !(info.dwFileAttributes & (FILE_ATTRIBUTE_REPARSE_POINT | FILE_ATTRIBUTE_DIRECTORY));
}

// ---- BCrypt SHA-256 ------------------------------------------------------

// The size limit of an MSI Setup will hash. BAKED keeps the original 128 MiB artifact cap; PASS
// accepts the release attestation's whole range (msi_size is at most 2^31-1), because there the
// attested exact size and hash are what bound the file.
#if SETUP_MODE_PASS
static constexpr LONGLONG kMaxHashedMsi = 2147483647LL;
#else
static constexpr LONGLONG kMaxHashedMsi = 128LL * 1024 * 1024;
#endif

static bool ComputeFileSha256(HANDLE hFile, std::array<BYTE, 32>& digest) {
    LARGE_INTEGER size = {};
    if (!GetFileSizeEx(hFile, &size) || size.QuadPart <= 0 || size.QuadPart > kMaxHashedMsi) return false;
    BCRYPT_ALG_HANDLE hAlgRaw = nullptr;
    if (!BCRYPT_SUCCESS(BCryptOpenAlgorithmProvider(
            &hAlgRaw, BCRYPT_SHA256_ALGORITHM, nullptr, 0))) return false;
    BcryptAlgGuard hAlg(hAlgRaw);

    BCRYPT_HASH_HANDLE hHashRaw = nullptr;
    if (!BCRYPT_SUCCESS(BCryptCreateHash(
            hAlg.get(), &hHashRaw, nullptr, 0, nullptr, 0, 0))) return false;
    BcryptHashGuard hHash(hHashRaw);

    std::vector<BYTE> buf(65536);
    for (;;) {
        DWORD read = 0;
        if (!ReadFile(hFile, buf.data(), static_cast<DWORD>(buf.size()), &read, nullptr)) return false;
        if (read == 0) break;
        if (!BCRYPT_SUCCESS(BCryptHashData(hHash.get(), buf.data(), read, 0))) return false;
    }
    return BCRYPT_SUCCESS(BCryptFinishHash(
        hHash.get(), digest.data(), static_cast<ULONG>(digest.size()), 0));
}

// ---- Staging directory ---------------------------------------------------

// Creates path with O:BA G:BA D:P (SYSTEM + Administrators full access, protected, inheritable).
// Returns false if the directory already exists (refuses to harden a pre-planted directory).
static bool CreateSecureDirectory(const std::wstring& path) {
    PSECURITY_DESCRIPTOR pSD = nullptr;
    if (!ConvertStringSecurityDescriptorToSecurityDescriptorW(
            L"O:BAG:BAD:P(A;OICI;FA;;;SY)(A;OICI;FA;;;BA)",
            SDDL_REVISION_1, &pSD, nullptr)) return false;
    LocalFreeGuard sdGuard(pSD);
    SECURITY_ATTRIBUTES sa = { sizeof(sa), pSD, FALSE };
    // CREATE_NEW semantics: fails with ERROR_ALREADY_EXISTS if path exists.
    if (!CreateDirectoryW(path.c_str(), &sa)) return false;
    return true;
}

static HANDLE CreateSecureFile(const std::wstring& path) {
    PSECURITY_DESCRIPTOR sd = nullptr;
    if (!ConvertStringSecurityDescriptorToSecurityDescriptorW(
        L"O:BAG:BAD:P(A;;FA;;;SY)(A;;FA;;;BA)", SDDL_REVISION_1, &sd, nullptr)) return INVALID_HANDLE_VALUE;
    LocalFreeGuard descriptor(sd);
    SECURITY_ATTRIBUTES sa = { sizeof(sa), sd, FALSE };
    return CreateFileW(path.c_str(), GENERIC_WRITE, 0, &sa, CREATE_NEW,
        FILE_ATTRIBUTE_NORMAL | FILE_FLAG_WRITE_THROUGH, nullptr);
}

// ---- File copy -----------------------------------------------------------

static bool CopyByHandle(HANDLE hSrc, HANDLE hDst) {
    std::vector<BYTE> buf(65536);
    for (;;) {
        DWORD read = 0;
        if (!ReadFile(hSrc, buf.data(), static_cast<DWORD>(buf.size()), &read, nullptr)) return false;
        if (read == 0) break;
        DWORD total = 0;
        while (total < read) {
            DWORD written = 0;
            if (!WriteFile(hDst, buf.data() + total, read - total, &written, nullptr) || written == 0) return false;
            total += written;
        }
    }
    return true;
}

// ---- Secure-erase then delete (best-effort; filesystem may retain copies) ----

static void SecureEraseFile(const std::wstring& path, DWORD knownSize) {
    HandleGuard h(CreateFileW(path.c_str(), GENERIC_WRITE, 0, nullptr,
                              OPEN_EXISTING,
                              FILE_ATTRIBUTE_NORMAL | FILE_FLAG_WRITE_THROUGH, nullptr));
    if (!h.valid()) { DeleteFileW(path.c_str()); return; }
    SetFilePointer(h.get(), 0, nullptr, FILE_BEGIN);
    std::vector<BYTE> zeros(knownSize, 0);
    DWORD written = 0;
    WriteFile(h.get(), zeros.data(), knownSize, &written, nullptr);
    FlushFileBuffers(h.get());
    SecureZeroMemory(zeros.data(), zeros.size());
    h.reset();
    DeleteFileW(path.c_str());
}

