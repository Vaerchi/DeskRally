// ---- RAII ----------------------------------------------------------------

struct HandleGuard {
    HANDLE h;
    explicit HandleGuard(HANDLE h = INVALID_HANDLE_VALUE) : h(h) {}
    ~HandleGuard() { reset(); }
    HandleGuard(const HandleGuard&) = delete;
    HandleGuard& operator=(const HandleGuard&) = delete;
    void reset(HANDLE nh = INVALID_HANDLE_VALUE) {
        if (h && h != INVALID_HANDLE_VALUE) CloseHandle(h);
        h = nh;
    }
    HANDLE get() const { return h; }
    bool valid() const { return h && h != INVALID_HANDLE_VALUE; }
};

struct ScopeExit {
    std::function<void()> action;
    bool active = true;
    ~ScopeExit() { if (active) action(); }
    void run() { if (active) { active = false; action(); } }
};

// Keep every checked directory open without delete sharing. A check by pathname alone permits
// a standard user to replace a checked parent with an SMB junction before the elevated file open.
struct PathLocks {
    std::vector<HANDLE> handles;
    ~PathLocks() { for (HANDLE handle : handles) CloseHandle(handle); }
    bool hold(const std::wstring& path, bool includeLeaf);
};

struct LocalFreeGuard {
    void* p;
    explicit LocalFreeGuard(void* p = nullptr) : p(p) {}
    ~LocalFreeGuard() { if (p) LocalFree(p); }
};

struct CoTaskFreeGuard {
    void* p;
    explicit CoTaskFreeGuard(void* p = nullptr) : p(p) {}
    ~CoTaskFreeGuard() { if (p) CoTaskMemFree(p); }
};

struct BcryptAlgGuard {
    BCRYPT_ALG_HANDLE h = nullptr;
    explicit BcryptAlgGuard(BCRYPT_ALG_HANDLE h = nullptr) : h(h) {}
    ~BcryptAlgGuard() { if (h) BCryptCloseAlgorithmProvider(h, 0); }
    BCRYPT_ALG_HANDLE get() const { return h; }
};

struct BcryptHashGuard {
    BCRYPT_HASH_HANDLE h = nullptr;
    explicit BcryptHashGuard(BCRYPT_HASH_HANDLE h = nullptr) : h(h) {}
    ~BcryptHashGuard() { if (h) BCryptDestroyHash(h); }
    BCRYPT_HASH_HANDLE get() const { return h; }
};

